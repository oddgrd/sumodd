  MX_TIM2_Init();
  /* USER CODE BEGIN 2 */

  // Ensure ring buffer is initialized before NEC ISR needs it.
  ring_buffer_init(&nec_commands, nec_buffer, sizeof(nec_buffer));

  if (HAL_TIM_IC_Start_IT(&htim16, TIM_CHANNEL_1) != HAL_OK)
  {
    Error_Handler();
  };
